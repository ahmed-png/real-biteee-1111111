const DEFAULT_IRAQI_RESPONSES = Object.freeze(IRAQI_REPLY_PAIRS.map(([trigger, response], index) => Object.freeze({
    id: `iraqi-${String(index + 1).padStart(3, '0')}`,
    trigger,
    response,
    enabled: true,
})));
const responseCandidateCache = new WeakMap();

function normalizeIraqiText(value) {
    return String(value || '')
        .normalize('NFKC')
        .toLowerCase()
        .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '')
        .replace(/\u0640/g, '')
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/ى/g, 'ي')
        .replace(/[ک]/g, 'ك')
        .replace(/[ی]/g, 'ي')
        .replace(/[!؟?.,،؛:()[\]{}"“”'’…\-_/\\|]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

function findMatchingResponse(message, responses = DEFAULT_IRAQI_RESPONSES) {
    const normalizedMessage = normalizeIraqiText(message);
    if (!normalizedMessage || !Array.isArray(responses)) return null;

    let candidates = responseCandidateCache.get(responses);
    if (!candidates) {
        candidates = responses
            .filter(item => item && item.enabled !== false && typeof item.trigger === 'string' && typeof item.response === 'string')
            .map(item => ({ item, trigger: normalizeIraqiText(item.trigger) }))
            .filter(({ trigger }) => trigger)
            .sort((left, right) => right.trigger.length - left.trigger.length);
        responseCandidateCache.set(responses, candidates);
    }

    const searchableMessage = ` ${normalizedMessage} `;
    const match = candidates.find(({ trigger }) => searchableMessage.includes(` ${trigger} `));
    return match?.item || null;
}

